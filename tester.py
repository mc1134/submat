def pretty_time(t):
    table = {
        0: "s",
        -1: "ms",
        -2: "us",
        -3: "ns",
        -4: "ps"
    }
    mult = 0
    if t <= 10**-12:
        return t, "s"
    if t < 1:
        while t < 1:
            mult -= 1
            t *= 10**3
    return t, table[mult]

